# ==========================================
# Python Operators - Simple Guide
# ==========================================

# 1. Arithmetic Operators (Maths ke liye)
print("--- 1. Arithmetic Operators ---")
a = 45
b = 65
print("Addition (a+b):", a + b)
print("Subtraction (a-b):", a - b)
print("Multiplication (a*b):", a * b)
print("Division (a/b):", a / b)
print("Modulus (Remainder):", a % b)
print("Floor Division:", a // b)
print("\n")

# 2. Relational Operators (Compare karne ke liye)
print("--- 2. Relational Operators ---")
a = 80
b = 100
print("Is a equal to b (a==b)?", a == b) 
print("Is a not equal to b (a!=b)?", a != b) 
print("Is a greater than b (a>b)?", a > b) 
print("Is a less than b (a<b)?", a < b) 
print("\n")

# 3. Assignment Operators (Value update karne ke liye)
print("--- 3. Assignment Operators ---")
num = 5
print("Initial num:", num)
num += 5
print("After num += 5:", num)
num -= 2
print("After num -= 2:", num)
num *= 3
print("After num *= 3:", num)
print("\n")

# 4. Logical Operators (True/False check karne ke liye)
print("--- 4. Logical Operators ---")
x = True
y = False
print("x and y is:", x and y)
print("x or y is:", x or y)
print("not x is:", not x)
